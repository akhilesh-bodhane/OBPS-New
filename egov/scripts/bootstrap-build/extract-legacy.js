// Extracts the Bootstrap-3-only rules from the old Bootstrap 3.3 stylesheet (bts.css) into src/_bs3-legacy.scss.
// They are kept verbatim so pages written with BS3 markup look and behave the same on Bootstrap 5.
// Usage: node extract-legacy.js <path-to-old-bts.css>
const fs = require('fs');
const postcss = require('postcss');

// selectors (regex sources) that must come from Bootstrap 3
const KEEP = new RegExp('(' + [
  '\\.glyphicon', '\\.panel', '\\.label\\b', '\\.label-', '\\.well', '\\.hidden-', '\\.visible-', '\\.pull-',
  '\\.btn-default', '\\.btn-xs', '\\.btn-group-xs', '\\.btn-block', '\\.caret\\b', '\\.thumbnail', '\\.jumbotron',
  '\\.media\\b', '\\.media-', '\\.help-block', '\\.form-horizontal', '\\.form-control-static', '\\.has-(error|success|warning|feedback)',
  '\\.control-label', '\\.dl-horizontal', '\\.img-responsive', '\\.img-circle', '\\.img-rounded', '\\.center-block',
  '\\.text-hide', '\\.sr-only', '\\.table-condensed', '\\.list-inline', '\\.pager', '\\.pagination', '\\.alert-dismiss',
  '\\.badge', '\\.checkbox', '\\.radio\\b', '\\.radio-inline', '\\.form-inline', '\\.form-group', '\\.input-lg', '\\.input-sm',
  '\\.affix', '\\.embed-responsive', '\\.close\\b', '\\.breadcrumb', '\\.page-header', '\\.lead\\b', '\\.hide\\b',
  '\\.nav\\b', '\\.nav-', '\\.navbar', '\\.dropdown-menu>', '\\.dropdown-menu > ', '\\.dropdown-menu-right', '\\.dropdown-menu-left',
  '\\.dropdown-header', '\\.dropdown-menu \\.divider', '\\.dropdown-backdrop', '\\.open\\s*>', '\\.progress-bar-(success|info|warning|danger)'
].join('|') + ')');
// selectors BS5 provides itself (only dropped when the selector is not also a KEEP match)
const SKIP = new RegExp('(' + [
  '\\.col-', '\\.row\\b', '\\.container\\b', '\\.input-group', '\\.table\\b', '\\.btn-group\\b', '\\.modal-dialog',
  '\\.fade\\b', '\\.collapse\\b', '\\.carousel', '\\.progress\\b'
].join('|') + ')');

const src = fs.readFileSync(process.argv[2], 'utf8');
const root = postcss.parse(src);
const out = postcss.root();

function filtered(rule) {
  const sel = rule.selectors.filter(s => KEEP.test(s) || (/^\.(nav|dropdown-menu)\s*(\{|$)/.test(s)));
  return sel.filter(s => !(SKIP.test(s) && !KEEP.test(s)));
}
function copy(rule) {
  const sel = filtered(rule);
  if (!sel.length) { return null; }
  const r = rule.clone(); r.selectors = sel; return r;
}
root.each(node => {
  if (node.type === 'rule') {
    const r = copy(node); if (r) { out.append(r); }
  } else if (node.type === 'atrule' && node.name === 'media') {
    const m = node.clone({ nodes: [] });
    node.each(n => { if (n.type === 'rule') { const r = copy(n); if (r) { m.append(r); } } });
    if (m.nodes.length) { out.append(m); }
  } else if (node.type === 'atrule' && node.name === 'font-face' && /Glyphicons/.test(node.toString())) {
    out.append(node.clone());
  }
});
fs.writeFileSync('src/_bs3-legacy.scss', '// GENERATED by extract-legacy.js from Bootstrap 3.3 bts.css - do not edit\n' + out.toString());
console.log('rules kept:', out.nodes.length);
